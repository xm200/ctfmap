const SIBERIA = new Set([
  'RU-ALT', 'RU-AL', 'RU-TY', 'RU-KK', 'RU-KYA', 'RU-IRK', 'RU-KEM',
  'RU-NVS', 'RU-OMS', 'RU-TOM',
]);

const FAR_EAST = new Set([
  'RU-AMU', 'RU-BU', 'RU-YEV', 'RU-ZAB', 'RU-KAM', 'RU-MAG', 'RU-PRI',
  'RU-SA', 'RU-SAK', 'RU-KHA', 'RU-CHU',
]);

export function getMacroZone(regionId: string): MacroZone {
  if (FAR_EAST.has(regionId)) return 'far-east';
  if (SIBERIA.has(regionId)) return 'siberia';
  return 'central';
}

